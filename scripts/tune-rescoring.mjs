/** Reproducible search of the rescoring weight on the decoder tuning set. */
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';
import {
  audioToIpa,
  errorRate,
  planRescoring,
  scoreJob,
} from '../src/index.js';
import { applyRescoring } from '../src/recognition/rescoring.js';
import {
  DECODER_VOICES,
  plannedPhones,
  renderDecoderText,
} from '../tests/helpers/decoder-material.js';
import { TUNING } from './decoder-tuning-material.mjs';

const weights = [0, 0.1, 0.2, 0.5, 1, 2, 5];
const rates = [16000, 8000];
const error = new Float64Array(weights.length);
let count = 0;
for (const [language, sentences] of Object.entries(TUNING)) {
  for (const [index, text] of sentences.entries()) {
    const voice = index % 2 === 0 ? DECODER_VOICES.male : DECODER_VOICES.female;
    for (const rate of rates) {
      const { samples, plan } = renderDecoderText(text, voice, rate, language);
      const reference = plannedPhones(plan).map(({ ipa }) => ipa);
      const decoded = audioToIpa(samples, rate, { voice, language, nbest: 10 });
      const preparation = planRescoring(decoded);
      const scores = preparation.jobs.map(scoreJob);
      weights.forEach((weight, i) => {
        const { ipa } = applyRescoring(decoded, preparation, scores, weight);
        error[i] += errorRate(reference, ipa, 'phone').rate;
      });
      count++;
    }
  }
  console.log('rescoring tuning complete', language);
}
const best = error.indexOf(Math.min(...error));
const source = [
  '// Generated by scripts/tune-rescoring.mjs. Unlicense.',
  `// Mean phone error across ${count} renders at 16000 and 8000 Hz, seed 1.`,
  '// Weight | Phone error rate',
  ...weights.map(
    (weight, i) => `// ${weight} | ${(error[i] / count).toFixed(6)}`
  ),
  `export const RESCORING_WEIGHT = ${weights[best]};`,
  '',
].join('\n');
writeFileSync(
  new URL('../src/recognition/rescoring-weights.js', import.meta.url),
  source
);
console.log(source);
