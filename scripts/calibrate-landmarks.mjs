#!/usr/bin/env node
/** Deterministic coordinate search of the fixed landmark decision tree.
 * Run by hand; no random search and no network. */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { calibrationMaterial } from './landmark-material.mjs';
import {
  BROAD_CLASSES,
  landmarkCandidates,
  classifyFrame,
  cleanClasses,
} from '../src/recognition/landmark-signals.js';

/** Inclusive allowed ranges. One search step = (max-min)/20. */
export const SEARCH_RANGES = Object.freeze({
  silence: [0, 20],
  voiced: [0.25, 0.75],
  fricativeZcr: [0.05, 0.55],
  fricativeGravity: [500, 3500],
  nasalDrop: [0, 40],
  nasalBelowPeak: [0, 12],
  glideBelowPeak: [0, 20],
  nucleusAboveNoise: [0, 20],
  nucleusDip: [0, 4],
  landmarkRise: [3, 23],
});
export const INITIAL_THRESHOLDS = Object.freeze({
  silence: 4,
  voiced: 0.45,
  fricativeZcr: 0.2,
  fricativeGravity: 1800,
  nasalDrop: 22,
  nasalBelowPeak: 3,
  glideBelowPeak: 6,
  nucleusAboveNoise: 10,
  nucleusDip: 2,
  landmarkRise: 9,
});

function bursts(item, rise) {
  item.burstCache ??= new Map();
  if (!item.burstCache.has(rise)) {
    const { frames } = item;
    const mask = new Uint8Array(frames.count);
    const candidates = landmarkCandidates(frames, rise);
    for (const lm of candidates) {
      if (lm.type === 'b+') {
        for (
          let t = lm.t;
          t < Math.min(frames.count, lm.t + Math.round(0.02 / frames.hop) + 1);
          t++
        ) {
          mask[t] = 1;
        }
      }
    }
    item.burstCache.set(rise, mask);
  }
  return item.burstCache.get(rise);
}

export function scoreThresholds(material, T) {
  const found = new Float64Array(8),
    total = new Float64Array(8);
  const rates = {};
  for (const item of material) {
    const { frames, sonority, peak, truth } = item;
    const mask = bursts(item, T.landmarkRise);
    const raw = new Uint8Array(frames.count);
    for (let t = 0; t < frames.count; t++) {
      const earlier = Math.max(0, t - Math.round(0.02 / frames.hop));
      raw[t] = classifyFrame(
        frames,
        sonority,
        t,
        peak[t],
        mask[t] && (raw[earlier] === 0 || raw[earlier] === 6),
        T
      );
    }
    const classes = cleanClasses(raw, frames.count, frames.hop);
    rates[frames.rate] ??= {
      found: new Float64Array(8),
      total: new Float64Array(8),
    };
    for (let t = 0; t < truth.length; t++) {
      if (truth[t] >= 0) {
        const k = truth[t];
        total[k]++;
        rates[frames.rate].total[k]++;
        if (classes[t] === k) {
          found[k]++;
          rates[frames.rate].found[k]++;
        }
      }
    }
  }
  const recalls = Array.from(total, (n, k) => (n ? found[k] / n : null));
  const present = recalls.filter((x) => x !== null);
  const perRate = Object.fromEntries(
    Object.entries(rates).map(([rate, v]) => [
      rate,
      Array.from(v.total, (n, k) => (n ? v.found[k] / n : null)),
    ])
  );
  return {
    mean: present.reduce((a, b) => a + b, 0) / present.length,
    recalls,
    perRate,
    frames: total.reduce((a, b) => a + b, 0),
  };
}

export function calibrate(material) {
  const T = { ...INITIAL_THRESHOLDS };
  let best = scoreThresholds(material, T).mean;
  for (let round = 0; round < 3; round++) {
    for (const [key, [low, high]] of Object.entries(SEARCH_RANGES)) {
      const previous = T[key];
      let chosen = previous;
      for (let step = 0; step <= 20; step++) {
        T[key] = Number((low + ((high - low) * step) / 20).toFixed(8));
        const score = scoreThresholds(material, T).mean;
        if (score > best + 1e-12) {
          best = score;
          chosen = T[key];
        }
      }
      T[key] = chosen;
    }
  }
  return { thresholds: T, ...scoreThresholds(material, T) };
}

export function thresholdSource(result) {
  const percent = (values) =>
    values.map((v) => (v === null ? 'n/a' : (v * 100).toFixed(3))).join(', ');
  const properties = Object.entries(result.thresholds)
    .map(([key, value]) => `  ${key}: ${value},`)
    .join('\n');
  return `/** Generated by node scripts/calibrate-landmarks.mjs.\n * Class order: ${BROAD_CLASSES.join(', ')}.\n * Recall (%): ${percent(result.recalls)}.\n${Object.entries(
    result.perRate
  )
    .map(([rate, values]) => ` * ${rate} Hz recall (%): ${percent(values)}.\n`)
    .join(
      ''
    )} * ${result.frames} labelled frames; three rounds, 21 values per coordinate.\n */\nexport const LANDMARK_THRESHOLDS = Object.freeze({\n${properties}\n});\n`;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const fractionAt = process.argv.indexOf('--fraction');
  const outAt = process.argv.indexOf('--out');
  const fraction = fractionAt < 0 ? 1 : Number(process.argv[fractionAt + 1]);
  const out =
    outAt < 0
      ? 'src/recognition/landmark-thresholds.js'
      : process.argv[outAt + 1];
  const material = calibrationMaterial(fraction);
  console.log(`calibration: ${material.length} renders`);
  const result = calibrate(material);
  writeFileSync(out, thresholdSource(result));
  console.log(JSON.stringify(result, null, 2));
}
