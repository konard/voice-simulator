#!/usr/bin/env node
/** Generate the relative level and duration cues of whispered consonants. Unlicense. */
import { writeFileSync } from 'node:fs';
import { pathToFileURL, URL } from 'node:url';
import { levelDb } from '../src/analysis/mode-features.js';
import { presetHeadConfig } from '../src/head-config.js';
import { getPhoneme, listSymbols } from '../src/ipa/inventory.js';
import { parseIpa } from '../src/ipa/parse.js';
import { PHONOTACTICS } from '../src/recognition/phonotactics.js';
import { synthesize } from '../src/synthesize.js';

export function whisperPairs() {
  const groups = new Map();
  for (const ipa of listSymbols()) {
    const { place, manner, voiced } = getPhoneme(ipa);
    if (!['plosive', 'fricative', 'lateral-fricative'].includes(manner)) {
      continue;
    }
    const key = `${place}/${manner}`;
    const pair = groups.get(key) ?? [];
    pair[Number(voiced)] = ipa;
    groups.set(key, pair);
  }
  const pairs = [...groups.values()].filter(
    ([unvoiced, voiced]) => unvoiced && voiced
  );
  const counterpart = new Map(
    pairs.flatMap(([a, b]) => [
      [a, b],
      [b, a],
    ])
  );
  const affricates = new Set([
    't͡s',
    't͡ʃ',
    't͡ɕ',
    'ʈ͡ʂ',
    ...Object.values(PHONOTACTICS).flatMap(({ units }) => units),
  ]);
  const found = new Map();
  for (const ipa of affricates) {
    const token = parseIpa(ipa).tokens[0];
    if (ipa.replace(/[ʰʱʲː]/gu, '') !== ipa || !token?.affricate) {
      continue;
    }
    const { stop, fricative } = token.affricate;
    const otherStop = counterpart.get(stop);
    const otherFricative = counterpart.get(fricative);
    if (otherStop && otherFricative) {
      const other = `${otherStop}͡${otherFricative}`;
      const pair = token.voiced ? [other, ipa] : [ipa, other];
      found.set(pair[0], pair);
    }
  }
  return pairs.concat([...found.values()]);
}

function measure(ipa, vowel, head) {
  const { plan, samples, sampleRate } = synthesize(
    `{W ${vowel}${ipa}${vowel} W}`,
    {
      ipa: true,
      head,
      tier: 'minimal',
      engine: 'js',
      seed: 1,
    }
  );
  const first = plan.segments.find((span) => span.token === plan.tokens[0]);
  const spans = plan.segments.filter((span) => span.token === plan.tokens[1]);
  const start = spans[0].start;
  const end = spans.at(-1).end;
  const level = (first, last) =>
    levelDb(samples, first * sampleRate, last * sampleRate);
  return [
    (end - start) / (first.end - first.start),
    level(start, end) - level(first.start, first.end),
  ];
}

function stats(values) {
  const mean = values.reduce((sum, value) => sum + value, 0) / values.length;
  const deviation = Math.sqrt(
    values.reduce((sum, value) => sum + (mean - value) ** 2, 0) / values.length
  );
  return [mean, deviation].map((value) => Number(value.toFixed(6)));
}

export function buildWhisperCues() {
  const voices = ['male', 'female'].map(presetHeadConfig);
  return whisperPairs().map((pair) =>
    pair.map((ipa) => {
      const observations = voices.flatMap((head) =>
        ['a', 'i', 'u'].map((vowel) => measure(ipa, vowel, head))
      );
      return [
        ipa,
        ...[0, 1].map((i) => stats(observations.map((value) => value[i]))),
      ];
    })
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const cues = buildWhisperCues();
  writeFileSync(
    new URL('../src/recognition/data/whisper-cues.js', import.meta.url),
    [
      '// Generated by scripts/build-whisper-cues.mjs. Unlicense.',
      '// A pair holds [IPA, [duration mean, SD], [relative dB mean, SD]] for each member.',
      'export const WHISPER_CUES = [',
      ...cues.map((pair) => `  ${JSON.stringify(pair)},`),
      '];',
      '',
    ].join('\n')
  );
}
