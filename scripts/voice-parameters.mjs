#!/usr/bin/env node
/**
 * Writes docs/VOICE-PARAMETERS.md (one table per parameter group: key,
 * unit, range, default, effect and source) and schemas/voice.schema.json
 * (voiceSchema of src/voice-file.js) from HEAD_PARAMETERS (issue 41).
 *
 *   node scripts/voice-parameters.mjs           write both files
 *   node scripts/voice-parameters.mjs --count   print the number of parameters
 *
 * tests/head-parameters.test.js and tests/voice-file.test.js fail when a
 * committed file differs from what this script writes.
 */

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { HEAD_GROUPS, HEAD_PARAMETERS } from '../src/head-config.js';
import { voiceSchema } from '../src/voice-file.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOCS_FILE = path.join(root, 'docs', 'VOICE-PARAMETERS.md');
export const SCHEMA_FILE = path.join(root, 'schemas', 'voice.schema.json');

const GROUP_TITLES = {
  anatomy: 'Anatomy: the tract, the mouth, the face, the teeth and the walls',
  folds: 'Folds: the vocal folds and their pulses',
  breathing: 'Breathing: lungs, airflow and noise sources',
  articulation: 'Articulation: timing, speeds and duration rules',
  expression: 'Expression: intonation, rhythm and level',
  microphone: 'Microphone: where the listener is and the room',
};

/** Markdown table cell: no pipes or line breaks. */
function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function unitText(unit) {
  if (unit === '1') {
    return '–';
  }
  return unit === 'x' ? '× (factor)' : unit;
}

function effectText(effect) {
  const direction = effect.sign > 0 ? 'rises' : 'falls';
  const conditions = [];
  if (effect.values) {
    conditions.push(`from ${effect.values[0]} to ${effect.values[1]}`);
  }
  if (effect.ipa) {
    conditions.push(effect.ipa);
  }
  if (effect.tier) {
    conditions.push(`tier ${effect.tier}`);
  }
  for (const [key, value] of Object.entries({
    ...effect.options,
    ...effect.head,
  })) {
    conditions.push(`${key} ${value}`);
  }
  const condition = conditions.length > 0 ? ` (${conditions.join(', ')})` : '';
  return `${effect.measure} ${direction}${condition}`;
}

function parameterRow(parameter) {
  const name = `\`${parameter.key}\`${parameter.advanced ? '' : ' ★'}`;
  return `| ${[
    `${name}<br>${parameter.label}`,
    unitText(parameter.unit),
    `${parameter.min} to ${parameter.max}`,
    parameter.default,
    effectText(parameter.effect),
    parameter.source,
  ]
    .map(cell)
    .join(' | ')} |`;
}

/** The text of docs/VOICE-PARAMETERS.md. */
export function voiceParametersMarkdown() {
  const lines = [
    '# Voice parameters',
    '',
    '<!-- Generated by `node scripts/voice-parameters.mjs` from HEAD_PARAMETERS; do not edit. -->',
    '',
    `A voice is one flat head object of ${HEAD_PARAMETERS.length} values. Voice files`,
    '(`src/voice-file.js`, `schemas/voice.schema.json`) write them per group,',
    'and the editor shows one section per group. ★ marks the parameters the',
    'editor shows by default; the others appear with "Show all parameters".',
    '',
    'The effect is the measure of `ˈmama ˈsasa` (IPA, tier `minimal`, fixed seed,',
    'see `tests/helpers/voice-measures.js`) that rises or falls when the value',
    'goes from its minimum to its maximum, checked by',
    '`tests/head-parameters.test.js` ("moves the sound in the documented',
    'direction"). Conditions in parentheses replace that utterance, tier,',
    'options or head values. A source `fitted: <file>` names the experiment',
    'that fitted the value.',
    '',
    '| Group | Parameters |',
    '| --- | --- |',
    ...HEAD_GROUPS.map(
      (group) =>
        `| [${group}](#${group}) | ${HEAD_PARAMETERS.filter((parameter) => parameter.group === group).length} |`
    ),
  ];
  for (const group of HEAD_GROUPS) {
    lines.push(
      '',
      `## ${group}`,
      '',
      `${GROUP_TITLES[group]}.`,
      '',
      '| Key | Unit | Range | Default | Effect | Source |',
      '| --- | --- | --- | --- | --- | --- |',
      ...HEAD_PARAMETERS.filter((parameter) => parameter.group === group).map(
        parameterRow
      )
    );
  }
  return `${lines.join('\n')}\n`;
}

/** The text of schemas/voice.schema.json. */
export function voiceSchemaText() {
  return `${JSON.stringify(voiceSchema(), null, 2)}\n`;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  if (process.argv.includes('--count')) {
    console.log(HEAD_PARAMETERS.length);
  } else {
    writeFileSync(DOCS_FILE, voiceParametersMarkdown());
    writeFileSync(SCHEMA_FILE, voiceSchemaText());
    console.log(
      `${path.relative(root, DOCS_FILE)} and ${path.relative(root, SCHEMA_FILE)}: ${HEAD_PARAMETERS.length} parameters`
    );
  }
}
