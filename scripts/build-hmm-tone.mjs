#!/usr/bin/env node
/**
 * Fit the tone stream of the Gaussian HMM recogniser (src/recognition/
 * hmm-tone.js) on rendered training files of experiments/issue-75-hmm-
 * render.mjs: per frame the tone features of the stored 8 kHz audio,
 * pooled by tone class and state of its label ("o@2", state 1 → "2#1"),
 * every other frame into "0" (every STRIDE-th of them, enough for a
 * mixture of six dimensions). Writes src/recognition/data/hmm-tone.js.
 * node scripts/build-hmm-tone.mjs <train.json...>
 * Environment: K (mixtures per key, 8), STRIDE (8), OUT (output file).
 * Unlicense.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { Buffer } from 'node:buffer';
import { hmmStatics } from '../src/recognition/hmm-features.js';
import {
  HMM_TONE_DIMS,
  hmmToneFeatures,
  toneKey,
} from '../src/recognition/hmm-tone.js';
import { fitGmm } from '../experiments/issue-75-hmm-model.mjs';

const K = Number(process.env.K ?? 8);
const STRIDE = Number(process.env.STRIDE ?? 8);
const OUT = process.env.OUT ?? 'src/recognition/data/hmm-tone.js';
const files = process.argv.slice(2);
if (!files.length) {
  console.error('usage: node scripts/build-hmm-tone.mjs <train.json...>');
  process.exit(1);
}

const pools = new Map();
let rest = 0;
for (const file of files) {
  for (const item of JSON.parse(readFileSync(file, 'utf8'))) {
    const b = Buffer.from(item.audio, 'base64');
    const pcm = new Int16Array(b.buffer, b.byteOffset, b.length / 2);
    const { statics } = hmmStatics(Float32Array.from(pcm, (v) => v / 32767));
    const n = Math.min(statics.length, item.frames);
    const f = hmmToneFeatures(
      statics.slice(0, n).map((v) => v[13] / 4),
      statics.slice(0, n).map((v) => v[14])
    );
    for (let t = 0; t < n; t++) {
      const key = toneKey(item.labels[t], item.states[t]);
      if (key === '0' && rest++ % STRIDE) {
        continue;
      }
      if (!pools.has(key)) {
        pools.set(key, []);
      }
      pools.get(key).push(f.slice(t * HMM_TONE_DIMS, (t + 1) * HMM_TONE_DIMS));
    }
  }
  console.log(file, [...pools].map(([k, v]) => `${k}:${v.length}`).join(' '));
}
const keys = [...pools.keys()].sort();
const round = (v) => Number(v.toPrecision(5));
const components = keys.flatMap((key, i) =>
  fitGmm(pools.get(key), K).map((c) => [
    i,
    round(Math.log(c.w)),
    ...[...c.mu].map(round),
    ...[...c.var].map((v) => round(Math.max(v, 1e-4))),
  ])
);
const data = { dims: HMM_TONE_DIMS, keys, components };
writeFileSync(
  OUT,
  `/* Generated by scripts/build-hmm-tone.mjs; see SOURCES.md. Unlicense. */\n// prettier-ignore\nexport const HMM_TONE = ${JSON.stringify(data)};\n`
);
console.log(`${OUT} ${keys.length} keys ${components.length} components`);
