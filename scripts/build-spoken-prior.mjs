#!/usr/bin/env node
/**
 * Write src/recognition/data/<lang>-spoken.js: the Common Voice sentence
 * text counts (CC0, data/lexicon/<lang>-counts.txt) of the shipped
 * recognition words. The HMM word decoder backs English words off to them,
 * since the pre-1926 books never saw everyday spoken words such as "hello"
 * (issue 181). Offline; rerun after build-recognition-data.mjs.
 * node scripts/build-spoken-prior.mjs [lang ...] (default: en)
 * Unlicense.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dataString } from './build-recognition-data.mjs';
import { getCounts } from '../src/recognition/data/index.js';

const ROOT = new globalThis.URL('../', import.meta.url);

/** `word count` lines, most frequent first. */
export function readSpokenCounts(text) {
  return text
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [word, count] = line.trim().split(/\s+/u);
      return [word, Number(count)];
    });
}

/**
 * The counts of the given shipped words, most frequent first (code-point
 * tie breaks), and the number of source tokens they are a share of.
 */
export function buildSpokenPrior(spoken, words) {
  const shipped = new Set(words);
  let total = 0;
  for (const [, count] of spoken) {
    total += count;
  }
  const entries = spoken
    .filter(([word, count]) => shipped.has(word) && count > 0)
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  return { total, entries };
}

export function writeSpokenPrior({ total, entries }, language, out) {
  const source = `data/lexicon/${language}-counts.txt`;
  writeFileSync(
    out,
    `/** Generated by scripts/build-spoken-prior.mjs from ${source}: Common\n` +
      ` * Voice sentence text counts (CC0 1.0) of the shipped recognition words. */\n` +
      `/* eslint local/no-changelog-comments: ["warn", {"checkStrings": false}] -- Corpus words are data. */\n` +
      `export const SPOKEN_WORDS = ${total};\n${dataString('SPOKEN', entries)}`
  );
}

function main() {
  const languages = process.argv.slice(2);
  for (const language of languages.length ? languages : ['en']) {
    const spoken = readSpokenCounts(
      readFileSync(
        new globalThis.URL(`data/lexicon/${language}-counts.txt`, ROOT),
        'utf8'
      )
    );
    const prior = buildSpokenPrior(
      spoken,
      getCounts(language).words.map(({ word }) => word)
    );
    const out = fileURLToPath(
      new globalThis.URL(`src/recognition/data/${language}-spoken.js`, ROOT)
    );
    writeSpokenPrior(prior, language, out);
    console.log(
      JSON.stringify({
        language,
        spokenWords: prior.total,
        words: prior.entries.length,
      })
    );
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
