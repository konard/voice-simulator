/** Select the original decoder weights' best grid point on distinct sentences. Unlicense. */
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';
import { errorRate, presetHeadConfig, synthesize } from '../src/index.js';
import {
  analyzeForDecode,
  decoderSettings,
  joinSegments,
  prepareIpaDecode,
  segmentsOf,
} from '../src/recognition/decode-pipeline.js';
import { decodeSearch } from '../src/recognition/decode-search.js';
import { TUNING } from './decoder-tuning-material.mjs';

const INITIAL = { duration: 0.5, class: 4, phonotactic: 1 };
const SCALES = [1, 0.5, 2];

function combinations() {
  const grid = [];
  for (const duration of SCALES) {
    for (const broadClass of SCALES) {
      for (const phonotactic of SCALES) {
        grid.push({
          weights: {
            duration: INITIAL.duration * duration,
            class: INITIAL.class * broadClass,
            phonotactic: INITIAL.phonotactic * phonotactic,
          },
          rate: 0,
        });
      }
    }
  }
  return grid;
}

const grid = combinations();
const sampleRate = 16000;
let count = 0;
for (const [language, sentences] of Object.entries(TUNING)) {
  for (const [index, sentence] of sentences.entries()) {
    const voice = presetHeadConfig(index % 2 === 0 ? 'male' : 'female');
    const options = { voice, language };
    const { samples, plan } = synthesize(sentence, {
      language,
      head: voice,
      sampleRate,
      solver: 'waveguide',
      engine: 'js',
      seed: 1,
    });
    const settings = decoderSettings(sampleRate, options);
    const analysis = analyzeForDecode(samples, sampleRate, options, settings);
    const { prepared, templates } = prepareIpaDecode(analysis, settings);
    const reference = plan.tokens
      .filter(({ kind }) => kind === 'vowel' || kind === 'consonant')
      .map(({ symbol }) => symbol);
    for (const entry of grid) {
      const { paths } = decodeSearch(prepared, settings.language, {
        ...settings,
        weights: entry.weights,
        lattice: false,
      });
      const ipa = joinSegments(
        segmentsOf(paths[0], prepared.times, templates, settings.language)
      );
      entry.rate += errorRate(reference, ipa, 'phone').rate;
    }
    count++;
  }
}
grid.sort((a, b) => a.rate - b.rate);
const { weights, rate } = grid[0];
const source = [
  '// Generated by scripts/tune-decoder.mjs. Unlicense.',
  `// Mean phone error rate ${(rate / count).toFixed(6)} on ${count} tuning sentences, seed 1.`,
  'export const DECODE_WEIGHTS = Object.freeze({',
  ...Object.entries(weights).map(([key, value]) => `  ${key}: ${value},`),
  '});',
  '',
].join('\n');
writeFileSync(
  new URL('../src/recognition/decode-weights.js', import.meta.url),
  source
);
console.log('decoder tuning', weights, 'phone error rate', rate / count);
