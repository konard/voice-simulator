#!/usr/bin/env node
/** Rebuild the source regressions from seeded waveguide synthesis. Unlicense. */
import { writeFileSync } from 'node:fs';
import {
  analyzeFrames,
  presetHeadConfig,
  synthesize,
  trackPitch,
} from '../src/index.js';
import { sampleState } from '../src/articulation/tract-shape.js';
import { CONSONANTS } from '../src/ipa/inventory.js';
import {
  energyReference,
  NOISE_CHANNELS,
  sourceFeatures,
} from '../src/recognition/inversion-source.js';
import { LANDMARK_SENTENCES } from './landmark-material.mjs';

const INPUTS = 6;
const COLUMNS = INPUTS + NOISE_CHANNELS.length;

/** Incremental QR: each new row is rotated out of the triangular factor.
 * The same rotations apply to all three response columns. */
function regression() {
  const upper = Array.from({ length: INPUTS }, () => new Float64Array(COLUMNS));
  const residual = new Float64Array(NOISE_CHANNELS.length);
  let count = 0;

  return {
    add(input, response) {
      const row = [...input, ...response];
      for (let i = 0; i < INPUTS; i++) {
        const length = Math.hypot(upper[i][i], row[i]);
        if (length === 0) {
          continue;
        }
        const c = upper[i][i] / length;
        const s = row[i] / length;
        for (let j = i; j < COLUMNS; j++) {
          const a = upper[i][j];
          const b = row[j];
          upper[i][j] = c * a + s * b;
          row[j] = c * b - s * a;
        }
      }
      for (let j = 0; j < residual.length; j++) {
        residual[j] += row[INPUTS + j] ** 2;
      }
      count++;
    },
    fit(j) {
      const model = new Float64Array(INPUTS);
      for (let i = INPUTS - 1; i >= 0; i--) {
        let value = upper[i][INPUTS + j];
        for (let k = i + 1; k < INPUTS; k++) {
          value -= upper[i][k] * model[k];
        }
        model[i] = value / upper[i][i];
      }
      return {
        weights: Array.from(model, (x) => Number(x.toPrecision(10))),
        rms: Math.sqrt(residual[j] / count),
      };
    },
  };
}

function accumulate(fit, text, head, sampleRate, options) {
  const { samples, plan } = synthesize(text, {
    head,
    sampleRate,
    solver: 'waveguide',
    engine: 'js',
    seed: 1,
    ...options,
  });
  const frames = analyzeFrames(samples, sampleRate);
  const pitch = trackPitch(frames);
  const ref = energyReference(frames.count);
  const truth = {};
  for (let t = 0; t < frames.count; t++) {
    const reference = ref(frames.energy[t], pitch.f0[t] > 0);
    if (frames.speech[t]) {
      sampleState(plan, frames.startTime + t * frames.hop, truth);
      fit.add(
        sourceFeatures(frames, t, reference),
        NOISE_CHANNELS.map((name) => truth[name])
      );
    }
  }
}

function calibrate(rate) {
  const fit = regression();
  for (const preset of ['male', 'female', 'child']) {
    const head = presetHeadConfig(preset);
    for (const [lang, text] of LANDMARK_SENTENCES) {
      accumulate(fit, text, head, rate, { lang });
    }
    for (const phone of Object.keys(CONSONANTS)) {
      for (const vowel of ['a', 'i', 'u']) {
        accumulate(fit, `${vowel}${phone}${vowel}`, head, rate, { ipa: true });
      }
    }
  }
  return NOISE_CHANNELS.map((name, j) => ({ name, ...fit.fit(j) }));
}

const lines = [
  '/** Generated by node scripts/calibrate-inversion.mjs. Unlicense. */',
  '// Coefficients multiply [1, energy - ref, gravity / 1000, zcr, periodicity, tilt].',
  '// RMS errors describe the fitted linear predictions before clamping.',
  '// prettier-ignore',
  'export const SOURCE_CHANNEL_MAPS = {',
];
for (const rate of [8000, 11025, 16000]) {
  const models = calibrate(rate);
  lines.push(`  ${rate}: {`);
  for (const { name, weights, rms } of models) {
    lines.push(
      `    // RMS ${rms.toFixed(6)}.`,
      `    ${name}: [`,
      ...weights.map((x) => `      ${x},`),
      '    ],'
    );
  }
  lines.push('  },');
  console.log(
    'inversion calibration',
    rate,
    models.map(({ name, rms }) => `${name}: ${rms.toFixed(6)}`).join(', ')
  );
}
lines.push('};', '');
writeFileSync(
  new globalThis.URL(
    '../src/recognition/source-channel-maps.js',
    import.meta.url
  ),
  lines.join('\n')
);
