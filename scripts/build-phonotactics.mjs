/** Count IPA word-internal transitions from the repository's dictionaries. Unlicense. */
import { readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';
import { textToIpa } from '../src/g2p/index.js';
import { lexiconWords, pronunciations } from '../src/g2p/lexicon.js';
import { ZH_READINGS } from '../src/g2p/lexicon/zh.js';
import { formatIpa, parseIpa } from '../src/ipa/parse.js';

function readLines(path) {
  return readFileSync(new URL(path, import.meta.url), 'utf8')
    .split(/\r?\n/u)
    .map((line) => line.split('#')[0].trim())
    .filter(Boolean);
}

function wordModel(readings) {
  const tokens = [...readings].map((ipa) =>
    parseIpa(ipa).tokens.filter(
      ({ kind }) => kind === 'vowel' || kind === 'consonant'
    )
  );
  const symbol = (token) =>
    formatIpa([
      {
        ...token,
        stress: 0,
        tone: null,
        symbol: token.symbol.replace(/[ːˑ]/gu, ''),
      },
    ]).normalize('NFC');
  const units = [...new Set(tokens.flatMap((word) => word.map(symbol)))].sort();
  const long = [
    ...new Set(
      tokens.flatMap((word) => word.filter((phone) => phone.long).map(symbol))
    ),
  ].sort();
  const width = units.length + 1;
  const ids = new Map(units.map((unit, index) => [unit, index]));
  const counts = new Uint16Array(width ** 2);
  for (const word of tokens) {
    if (!word.length) {
      continue;
    }
    const chain = [
      units.length,
      ...word.map((phone) => ids.get(symbol(phone))),
      units.length,
    ];
    for (let i = 1; i < chain.length; i++) {
      const index = chain[i - 1] * width + chain[i];
      counts[index] = Math.min(65535, counts[index] + 1);
    }
  }
  return { units, counts, long };
}

function readings(language, words) {
  return [...new Set(words)].map((word) => textToIpa(word, { language }).ipa);
}

const hindi = readLines('./data/hindi-words.txt');
if (new Set(hindi).size !== hindi.length || hindi.length < 500) {
  throw new Error('Expected at least 500 distinct Hindi words');
}
const sources = {
  en: [...lexiconWords('en')].map((word) => pronunciations('en', word)[0]),
  ru: readings(
    'ru',
    readLines('../data/lexicon/ru-stress.txt').map((line) =>
      line.replace(/[=+|]/gu, '')
    )
  ),
  hi: readings('hi', hindi),
  zh: readings(
    'zh',
    ZH_READINGS.groups.flatMap((line) =>
      line.split(' ').map((group) => [...group.split('=')[1]][0])
    )
  ),
};

const entries = Object.entries(sources).map(([language, words]) => {
  const { units, counts, long } = wordModel(words);
  const rows = [];
  for (let first = 0; first < counts.length; first += 24) {
    rows.push(`      ${counts.slice(first, first + 24).join(', ')},`);
  }
  return `  ${language}: {\n    units: ${JSON.stringify(units)},\n    long: ${JSON.stringify(long)},\n    counts: new Uint16Array([\n${rows.join('\n')}\n    ]),\n  },`;
});
const source = [
  '// Generated by scripts/build-phonotactics.mjs. Unlicense.',
  '// The last row and column are the word boundary (#).',
  '// prettier-ignore',
  'export const PHONOTACTICS = {',
  ...entries,
  '};',
  '',
].join('\n');
if (Buffer.byteLength(source) > 200_000) {
  throw new Error('Phonotactics data exceeds 200 kB');
}
writeFileSync(
  new URL('../src/recognition/phonotactics.js', import.meta.url),
  source
);
